DICT = Path(__file__).resolve().parent.parent / 'translations' / 'dictionary_zh.json'

def main():
    with open(DICT, encoding='utf-8') as fh:
        doc = json.load(fh)
    t = doc['translations']
    added = existed = 0
    for k, v in T_TERMS.items():
        if k in t:
            existed += 1
        else:
            t[k] = v
            added += 1
    doc['translations'] = t
    with open(DICT, 'w', encoding='utf-8') as fh:
        json.dump(doc, fh, ensure_ascii=False, indent=2)
        fh.write('\n')
    print('terms:', len(T_TERMS), ' added:', added, ' existed:', existed)

if __name__ == '__main__':
    main()
